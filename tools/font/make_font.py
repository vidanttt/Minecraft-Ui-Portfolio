SPACE_ADVANCE = 4


def pixels(rows, bold=False):
    pts = set()
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch == "#":
                y = 6 - r  # row 6 sits on the baseline (y=0)
                pts.add((c, y))
                if bold:
                    pts.add((c + 1, y))
    return pts


def outline(pts):
    """Trace the union of unit squares into clockwise (TrueType) contours."""
    edges = {}
    def add(a, b):
        if (b, a) in edges:
            del edges[(b, a)]
        else:
            edges[(a, b)] = True
    for (x, y) in pts:
        # clockwise in y-up space
        add((x, y), (x, y + 1))
        add((x, y + 1), (x + 1, y + 1))
        add((x + 1, y + 1), (x + 1, y))
        add((x + 1, y), (x, y))
    out = {}
    for (a, b) in edges:
        out.setdefault(a, []).append(b)
    contours = []
    while out:
        start = next(iter(out))
        contour = [start]
        prev = None
        cur = start
        while True:
            nexts = out[cur]
            if len(nexts) == 1:
                nxt = nexts[0]
            else:
                # at a diagonal touch, take the clockwise-most turn so loops stay simple
                dx0, dy0 = (cur[0] - prev[0], cur[1] - prev[1]) if prev else (0, 1)
                def score(p):
                    dx, dy = p[0] - cur[0], p[1] - cur[1]
                    cross = dx0 * dy - dy0 * dx
                    return cross  # negative = right turn (clockwise)
                nxt = min(nexts, key=score)
            nexts.remove(nxt)
            if not nexts:
                del out[cur]
            prev, cur = cur, nxt
            if cur == start:
                break
            contour.append(cur)
        # drop collinear points
        simp = []
        n = len(contour)
        for i in range(n):
            p0, p1, p2 = contour[i - 1], contour[i], contour[(i + 1) % n]
            if (p1[0] - p0[0]) * (p2[1] - p1[1]) - (p1[1] - p0[1]) * (p2[0] - p1[0]) != 0:
                simp.append(p1)
        contours.append(simp)
    return contours


def build(path, bold):
    fam = "Blockfolio"
    style = "Bold" if bold else "Regular"
    glyph_order = [".notdef", "space"]
    cmap = {32: "space"}
    glyphs = {}
    metrics = {}

    pen = TTGlyphPen(None)
    for (x0, y0, x1, y1) in [(0, 0, 5, 7)]:
        pen.moveTo((x0 * PX, y0 * PX)); pen.lineTo((x0 * PX, y1 * PX))
        pen.lineTo((x1 * PX, y1 * PX)); pen.lineTo((x1 * PX, y0 * PX)); pen.closePath()
        pen.moveTo((1 * PX, 1 * PX)); pen.lineTo((4 * PX, 1 * PX))
        pen.lineTo((4 * PX, 6 * PX)); pen.lineTo((1 * PX, 6 * PX)); pen.closePath()
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (6 * PX, 0)
    glyphs["space"] = TTGlyphPen(None).glyph()
    metrics["space"] = ((SPACE_ADVANCE + (1 if bold else 0)) * PX, 0)

    for ch, rows in G.items():
        name = "uni%04X" % ord(ch)
        glyph_order.append(name)
        cmap[ord(ch)] = name
        width = len(rows[0]) + (1 if bold else 0)
        pen = TTGlyphPen(None)
        for contour in outline(pixels(rows, bold)):
            pen.moveTo((contour[0][0] * PX, contour[0][1] * PX))
            for p in contour[1:]:
                pen.lineTo((p[0] * PX, p[1] * PX))
            pen.closePath()
        glyphs[name] = pen.glyph()
        metrics[name] = ((width + 1) * PX, 0)

    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    # recompute lsb from glyph bounds
    glyf = fb.font["glyf"]
    hmtx = {}
    for name in glyph_order:
        gl = glyf[name]
        gl.recalcBounds(glyf)
        lsb = getattr(gl, "xMin", 0) if gl.numberOfContours else 0
        hmtx[name] = (metrics[name][0], lsb)
    fb.setupHorizontalMetrics(hmtx)
    fb.setupHorizontalHeader(ascent=1125, descent=-250)
    fb.setupNameTable({
        "familyName": fam,
        "styleName": style,
        "copyright": "Original pixel font created for this portfolio. Free to use.",
        "uniqueFontIdentifier": f"{fam}-{style}",
        "fullName": f"{fam} {style}",
        "psName": f"{fam}-{style}",
    })
    fb.setupOS2(version=4,
        sTypoAscender=1125, sTypoDescender=-250, sTypoLineGap=0,
        usWinAscent=1125, usWinDescent=250,
        usWeightClass=700 if bold else 400,
        fsSelection=(0x20 if bold else 0x40) | 0x80,
        sxHeight=5 * PX, sCapHeight=7 * PX,
    )
    fb.setupPost()
    fb.setupHead(unitsPerEm=1000, macStyle=1 if bold else 0)
    fb.font.flavor = "woff2"
    fb.save(path)
    print("wrote", path, len(G), "glyphs")


out = sys.argv[1]
build(out + "/Blockfolio-Regular.woff2", False)
build(out + "/Blockfolio-Bold.woff2", True)
